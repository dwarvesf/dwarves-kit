#!/usr/bin/env bash
# owners-seed.sh -- hook script for the OWNERS.md manifest row. Prints a full OWNERS.md with one
# row for every script and workflow in the merged manifest (every group, even under --only), so a
# freshly stamped repo passes its own owners check. The repo owns the file after the first write.
# Env from lib/stamp.sh: STAMP_ALL_TARGETS_FILE, STAMP_VALUES_FILE. Arg 1: the target repo.
set -uo pipefail
owner="$(awk -F'\t' '$1=="OWNER"{print $2; exit}' "$STAMP_VALUES_FILE")"
[ -n "$owner" ] || { echo "owners-seed: no OWNER value" >&2; exit 1; }

cat <<'HEAD'
# Owners

## Rule

- Every script, workflow and scheduled or deployed job has one owner.
- An owner is a GitHub login (`@login`) or a named agent. An agent owner also names a sponsor: the human who answers for that agent.
- The owner keeps it working, reviews changes to it, and retires it.
- A PR that adds a script, a workflow or a job adds its row in the same PR.
- Claiming ownership is editing the row in a PR. `scripts/check-owners.sh` fails CI when a file has no row, a row points at a missing path, or an owner or a needed sponsor is empty.

## Scripts and workflows

| Path | What it does | Owner | Sponsor |
|---|---|---|---|
HEAD

LC_ALL=C sort "$STAMP_ALL_TARGETS_FILE" | while IFS= read -r p; do
  case "$p" in
    scripts/test-*.sh) what="Test for scripts/${p#scripts/test-}";;
    scripts/*) what="Generated by the team stamp";;
    .github/workflows/*) what="CI workflow generated by the team stamp";;
    *) continue;;
  esac
  printf '| `%s` | %s | @%s | |\n' "$p" "$what" "$owner"
done
